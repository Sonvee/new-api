import { CircleQuestionMark } from 'lucide-react'
import { useTranslation } from 'react-i18next'

import { Button } from '@/components/ui/button'
import { Separator } from '@/components/ui/separator'
import {
  Tooltip,
  TooltipContent,
  TooltipProvider,
  TooltipTrigger,
} from '@/components/ui/tooltip'

/** 在 Token 表头说明缓存命中率的口径及常见下降原因。 */
export function TokenCacheHelp() {
  const { t } = useTranslation()

  return (
    <TooltipProvider delay={200}>
      <Tooltip>
        <TooltipTrigger
          render={
            <Button
              type='button'
              variant='ghost'
              size='icon-xs'
              className='text-muted-foreground hover:text-foreground size-5 cursor-help'
              aria-label={t('Cache hit rate help')}
            />
          }
        >
          <CircleQuestionMark className='size-3.5' aria-hidden='true' />
        </TooltipTrigger>
        <TooltipContent
          side='bottom'
          align='start'
          className='w-85 max-w-[calc(100vw-2rem)] py-2 text-left text-xs leading-relaxed font-normal whitespace-normal'
        >
          <div className='space-y-2'>
            <div className='space-y-1'>
              <p>
                {t('Input: input tokens excluding cache reads and cache writes.')}
              </p>
              <p>
                {t('Output: tokens generated by the model for this request.')}
              </p>
              <p>
                {t('Cache read: input tokens reused from an existing cache.')}
              </p>
              <p>
                {t(
                  'Cache write: input tokens written to a cache for reuse by later requests.'
                )}
              </p>
            </div>
            <Separator className='bg-background/20' />
            <div className='space-y-1 font-medium'>
              <p>{t('Total input = input + cache read + cache write')}</p>
              <p>{t('Cache hit rate = cache read / total input')}</p>
            </div>
            <Separator className='bg-background/20' />
            <p className='font-medium'>
              {t('Possible reasons for a lower cache hit rate')}
            </p>
            <ul className='list-disc space-y-1 pl-4'>
              <li>
                {t(
                  'Changes to prompt prefixes, tool definitions, or message order.'
                )}
              </li>
              <li>
                {t('Conversation history is compressed, rewritten, or truncated.')}
              </li>
              <li>
                {t('Long gaps between requests allow cached content to expire.')}
              </li>
              <li>
                {t('More new input is sent without matching an existing cache.')}
              </li>
              <li>
                {t(
                  'Switching models or upstream providers may prevent cache reuse.'
                )}
              </li>
            </ul>
          </div>
        </TooltipContent>
      </Tooltip>
    </TooltipProvider>
  )
}
